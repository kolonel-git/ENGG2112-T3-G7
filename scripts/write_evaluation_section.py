"""Generate Farhan's report section from published validation and frozen test tables (D-069)."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from wt_predmaint.config import load_protocol

ROOT = Path(__file__).resolve().parents[1]


def interval(row: pd.Series, metric: str) -> str:
    return f"{row[metric]:.3f} [{row[f'{metric}_lo']:.3f}, {row[f'{metric}_hi']:.3f}]"


def main() -> None:
    cfg = load_protocol()
    table = pd.read_csv(ROOT / "reports/tables/t0_validation.csv", float_precision="round_trip")
    test = pd.read_csv(ROOT / "reports/tables/test_results.csv")
    burden = pd.read_csv(ROOT / "reports/tables/alert_budget_validation.csv")
    if not table.split.eq("val").all():
        raise ValueError("the development report requires validation results only")
    ev, splits, labels = cfg["evaluation"], cfg["splits"], cfg["labels"]
    budget = float(ev["false_alarm_budget_per_turbine_month"])
    lines = [
        "# Evaluation and alert cost",
        "",
        "Report section by Farhan, generated by `scripts/write_evaluation_section.py` (D-069). "
        "Validation and the single frozen test run (D-060/D-061) are reported separately. "
        "Published-table consistency is checked; independent reproduction from original "
        "R2/LightGBM validation and test scores remains pending their transfer.",
        "",
        "## Evaluation design",
        "",
        f"We fitted models on {', '.join(map(str, splits['train_years']))}, "
        "selected model settings "
        f"and alert thresholds on {', '.join(map(str, splits['val_years']))}, and reserved "
        f"{', '.join(map(str, splits['test_years']))} for the frozen evaluation "
        "(2026 is partial through April). The time split avoids mixing neighbouring days across "
        f"training and evaluation. Labels purge rows whose {labels['exclusion_end_days']}-day "
        "horizon crosses a split boundary. "
        "Train-only preprocessing and healthy-reference fitting follow the shared model contract. "
        "Every day with features receives a score for plotting; metrics include only labelled "
        "turbine-days, excluding in-episode, exclusion-zone, purged, censored and poorly observed "
        "days. An episode is evaluable only if a labelled scored day exists in its warning window.",
        "",
        f"The official budget is **{budget:g} false alarm per turbine-month**. An alert occurs "
        "when the score is strictly greater than its threshold; a false alarm is an alert on "
        f"a negative labelled day. Exposure is labelled turbine-days divided by "
        f"{ev['days_per_month']:g}, including positive and negative days. It is not full calendar "
        "fleet exposure. The validation threshold allows at most the floor of budget times "
        "exposure false-alert days. Tied scores remain together and may leave budget unused. "
        "Test uses that threshold unchanged, so its realised rate can exceed the allowed "
        "validation budget and must still be reported.",
        "",
        "PR-AUC is computed as average precision over labelled days, with prevalence as the "
        "constant-score reference. Episode recall is the share of evaluable episodes with at "
        f"least one alert 1 to {labels['positive_window_days']} days before the start. "
        "Median lead time uses the earliest "
        "such alert for each detected episode and excludes missed episodes. One alert may "
        "cover overlapping episode windows; consecutive alerts are not consolidated into "
        "visits. There is no cooldown or one-to-one matching rule.",
        "",
        f"Intervals use {ev['bootstrap_resamples']} turbine bootstrap resamples with replacement, "
        f"a {100 * ev['ci_level']:g}% percentile interval and seed {cfg['seed']}. Entire turbine "
        "histories are resampled because adjacent feature and label windows overlap. Thresholds "
        "stay fixed across bootstrap draws. These intervals describe turbine variability "
        "conditional on the fitted model and selected threshold; they do not include model "
        "selection uncertainty or establish transfer to another wind farm.",
        "",
        "## Validation results at the official budget",
        "",
        "Both targets measure inferred operational episodes, rather than confirmed component "
        "failures. Target A uses daily fault time; B uses SCADA-derived stops. They are related "
        "cross-checks. The random-score reference is repeated beside every episode recall, "
        "because a long warning window can be hit by chance. Day-level PR-AUC and episode "
        "recall answer different questions; improvement in one does not guarantee the other.",
        "",
        f"| Target | Model | PR-AUC [{100 * ev['ci_level']:g}% interval] | "
        f"Episode recall [{100 * ev['ci_level']:g}% interval] | Random recall | "
        "Median lead (days) | Realised FA / turbine-month | Detected / evaluable |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for _, r in table.loc[table.variant.eq("all")].iterrows():
        lead = "undefined" if pd.isna(r.median_lead_days) else f"{r.median_lead_days:g}"
        lines.append(
            f"| {r.target} | {r.model} | {interval(r, 'pr_auc')} | {interval(r, 'recall')} | "
            f"{r.random_floor_recall:.3f} | {lead} | {r.false_alarms_per_turbine_month:.3f} | "
            f"{r.n_detected} / {r.n_episodes} |"
        )
    lines += [
        "", "## Frozen test results", "",
        "Settings were frozen in D-060 and the once-only run is recorded in D-061. "
        "This section copies the committed test export; it does not rerun models. "
        "Every PR-AUC interval contains its matching random-score point estimate. "
        "This interval comparison is not a paired significance test or proof of equivalence. "
        "The validation ranking did not carry into test. R1 and R2 exceed the official "
        "false-alarm budget on test, so their recall is not performance at that budget.",
        "",
        "| Target | Model | PR-AUC [95% interval] | Episode recall [95% interval] | "
        "Random recall | Median lead (days) | Realised FA / turbine-month | Detected / evaluable |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for r in test.itertuples(index=False):
        row = pd.Series(r._asdict())
        lead = "undefined" if pd.isna(r.median_lead_days) else f"{r.median_lead_days:g}"
        lines.append(
            f"| {r.target} | {r.model} | {interval(row, 'pr_auc')} | {interval(row, 'recall')} | "
            f"{r.random_floor_recall:.3f} | {lead} | {r.false_alarms_per_turbine_month:.3f} | "
            f"{r.n_detected} / {r.n_episodes} |"
        )
    full = table.loc[table.variant.eq("all") & table.model.ne("B0b_random")]
    wins = full.recall.gt(full.random_floor_recall).any()
    lines += [
        "",
        ("Some model recall point estimates exceed the random floor; consult the table for scope."
         if wins else "No available baseline exceeds the random-score episode recall point "
         "estimate at the official budget. Ranking performance alone therefore does not "
         "demonstrate useful early warning at this operating point."),
        "",
        "## Alert burden and missed episodes",
        "",
        "The validation sweep holds scores and model settings fixed and recalibrates the "
        "threshold separately at each configured budget. F27 plots false-alert days against "
        "missed evaluable episodes for both targets and both fleet variants; diamonds mark "
        "the official budget. The companion analysis includes all models and the random "
        "floor at every budget. The following reference-model check retains turbine 2304515 "
        "in the primary fleet and excludes it in the sensitivity run.",
        "",
        "| Target | Fleet | Model | False-alert days | Total labelled alert days | "
        "Missed / evaluable | Recall | Random recall |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    reference = burden.loc[burden.budget.eq(budget) & burden.model.eq("R1_zscore")]
    for r in reference.itertuples(index=False):
        lines.append(
            f"| {r.target} | {r.variant} | {r.model} | {r.false_alert_days} | "
            f"{r.labelled_alert_days} | {r.missed_episodes} / {r.n_episodes} | "
            f"{r.recall:.3f} | {r.random_floor_recall:.3f} |"
        )
    lines += [
        "",
        "False-alert days approximate review burden; missed episodes approximate the "
        "coverage lost when alerts are restricted. Total labelled alert days include "
        "alerts on positive days too. Alerts on unlabelled days are scored for plots but "
        "excluded from this burden estimate, so it is not the complete workload of an "
        "always-on deployment. Repeated alerts can refer to the same episode. Neither "
        "alert days nor missed inferred episodes can be equated with maintenance visits, "
        "prevented failures or lost energy. The dataset provides no verified visit cost, "
        "failure cost or intervention benefit, so we do not estimate currency savings "
        "or choose an economic optimum. The official budget stays fixed.",
        "",
        "The budget sweep is descriptive validation analysis. Settings and thresholds were "
        "selected using this same period, so differences across sampled budgets are not "
        "held-out performance or significance tests. The turbine-exclusion result is a "
        "sensitivity check, not a reason to discard a difficult turbine from the headline "
        "fleet. Sensor gaps, outage months, drift and unverified fault-time semantics "
        "limit the interpretation of both targets.",
        "",
        "![False-alert days versus missed episodes](figures/04_evaluation/"
        "F27_alert_burden_vs_missed_episodes.png)",
        "",
        "## Sources and audit scope",
        "",
        "Tables come from [validation T0](tables/t0_validation.csv), the "
        "[frozen test export](tables/test_results.csv) and the "
        "[validation budget sweep](tables/alert_budget_validation.csv). "
        "F27 includes R2 and both frozen LightGBM variants. Its values come from the "
        "committed sweep; new model scores are not available locally to regenerate that sweep.",
        "",
        "The [published-table audit](tables/published_table_audit.csv) checks exports against "
        "runner tables, matching floors, threshold carryover, count ratios and interval "
        "consistency. It does not reproduce predictions, metrics or bootstrap intervals. "
        "The earlier [score audit](tables/evaluation_audit.csv) covers only the previous "
        "36 validation rows and is historical, not sign-off of current T0. "
        "See [Farhan's review](../docs/EVALUATION_REVIEW.md) for the remaining artefact request.",
        "",
        "Methods follow D-009, D-020, D-024 and D-069 in "
        "[the decision log](../docs/project/DECISIONS.md). Rebuild this section with "
        "`python scripts/write_evaluation_section.py`. Obtain original saved validation/test "
        "scores and the frozen protocol before using `scripts/check_evaluation_results.py` "
        "for complete numerical reproduction; never refit, rescore or retune test.",
        "",
    ]
    path = ROOT / "reports/EVALUATION_AND_COST.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
