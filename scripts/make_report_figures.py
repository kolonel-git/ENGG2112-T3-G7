"""Build every report figure into reports/figures/<folder>/ and write reports/figures/README.md.

Each figure is a registered function in src/wt_predmaint/reporting/. Figures read the interim data
and report tables produced by the other scripts and use validation years only for model results.

    python scripts/make_report_figures.py                 # all figures
    python scripts/make_report_figures.py --only F15 F17  # some figures
    python scripts/make_report_figures.py --index-only    # rewrite the index without drawing
"""

from __future__ import annotations

import argparse
from pathlib import Path

from wt_predmaint.reporting import (  # noqa: F401  (registers the figures)
    figures_data,
    figures_eval,
    figures_explore,
    figures_nbm,
    figures_robust,
)
from wt_predmaint.reporting.context import Ctx
from wt_predmaint.reporting.style import REGISTRY, FigureSpec, apply_style, save

ROOT = Path(__file__).resolve().parents[1]
FIG_DIR = ROOT / "reports" / "figures"


def write_index(specs: list[FigureSpec]) -> Path:
    lines = [
        "# Report figures",
        "",
        "Generated by `scripts/make_report_figures.py` (D-025); do not edit by hand.",
        "Every figure is a registered function in `src/wt_predmaint/reporting/`.",
        "Model results use validation years only: the test years (2023 to 2026-04) are scored",
        "once for frozen configurations. Colours follow the project palette: target A is blue",
        "and target B is orange wherever both appear.",
        "",
        "| ID | Figure | Report section | File |",
        "|---|---|---|---|",
    ]
    for s in specs:
        lines.append(f"| {s.fig_id} | {s.title} | {s.section} | [{s.relpath}]({s.relpath}) |")
    lines.append("")
    for s in specs:
        lines += [f"## {s.fig_id}: {s.title}", "", f"![{s.title}]({s.relpath})", "",
                  f"- **Takeaway:** {s.message}", f"- **Report section:** {s.section}",
                  f"- **Built from:** {s.sources}"]  # fmt: skip
        if s.caveats:
            lines.append(f"- **Read with:** {s.caveats}")
        lines.append("")
    path = FIG_DIR / "README.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--only", nargs="*", help="figure ids, for example F15 F17")
    p.add_argument("--index-only", action="store_true")
    p.add_argument("--interim", type=Path)
    args = p.parse_args()

    specs = sorted(REGISTRY, key=lambda s: s.fig_id)
    if args.index_only:
        print(f"wrote {write_index(specs)}")
        return
    chosen = [s for s in specs if not args.only or s.fig_id in set(args.only)]
    if not chosen:
        raise SystemExit(f"no figure matches {args.only}; known: {[s.fig_id for s in specs]}")
    apply_style()
    ctx = Ctx(interim=args.interim)
    for spec in chosen:
        assert spec.func is not None
        save(spec.func(ctx), FIG_DIR / spec.relpath)
        print(f"{spec.fig_id}  {spec.relpath}")
    print(f"wrote {write_index(specs)}")


if __name__ == "__main__":
    main()
