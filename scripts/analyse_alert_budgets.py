"""Build validation burden tables from a freshly reproduced T0 and its score files.

Run make_baseline_table.py first. No fitting or test-scoring option is provided here.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

from wt_predmaint.config import load_protocol
from wt_predmaint.evaluation.budgets import add_random_comparison, budget_sweep
from wt_predmaint.evaluation.metrics import episodes_in_split
from wt_predmaint.models.base import attach_labels, labelled

ROOT = Path(__file__).resolve().parents[1]


def write_readout(table: pd.DataFrame, path: Path, official_budget: float) -> None:
    """Summarise computed R1/random comparisons without choosing a new budget."""
    lines = [
        "# Validation alert-burden analysis",
        "",
        "Generated by `scripts/analyse_alert_budgets.py` (D-054). Models and their selected "
        "settings stay fixed; each budget chooses its own threshold on validation. "
        f"The official budget remains {official_budget:g} false alarm per turbine-month. "
        "No test scores are used.",
        "",
        "## All available models at the official budget",
        "",
        "Every model present in the input validation table is included automatically, including "
        "newly registered models after their settings are frozen. Recall is paired with the "
        "random floor for the same target, fleet and budget.",
        "",
        "| Target | Fleet | Model | False-alert days | Missed / evaluable episodes | Recall | "
        "Random recall |",
        "|---|---|---|---:|---:|---:|---:|",
    ]
    official = table.loc[table.budget.eq(official_budget)]
    for r in official.itertuples(index=False):
        lines.append(
            f"| {r.target} | {r.variant} | {r.model} | {r.false_alert_days} | "
            f"{r.missed_episodes} / {r.n_episodes} | {r.recall:.3f} | "
            f"{r.random_floor_recall:.3f} |"
        )
    lines += [
        "",
        "## R1 versus the random floor across budgets",
        "",
        "R1 is retained as the reference baseline for this sweep. This table compares episode "
        "recall with random scores at the same allowed budget; it does not select the best model "
        "or budget for deployment.",
        "",
        "| Target | Allowed budget | R1 false-alert days | R1 detected / evaluable episodes | "
        "R1 missed episodes | R1 recall | Random recall | Recall difference |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    primary = table.loc[table.variant.eq("all") & table.model.eq("R1_zscore")]
    for r in primary.itertuples(index=False):
        lines.append(
            f"| {r.target} | {r.budget:g} | {r.false_alert_days} | "
            f"{r.n_detected} / {r.n_episodes} | {r.missed_episodes} | {r.recall:.3f} | "
            f"{r.random_floor_recall:.3f} | {r.recall_minus_random_floor:+.3f} |"
        )
    lines += ["", "## Fleet sensitivity", ""]
    reference = table.loc[table.model.eq("R1_zscore")]
    for (target, variant), frame in reference.groupby(["target", "variant"]):
        wins = frame.loc[frame.recall_minus_random_floor.gt(0), "budget"].tolist()
        text = ", ".join(f"{b:g}" for b in wins) or "none"
        lines.append(
            f"- {target}, {variant}: R1 exceeds the random recall point estimate "
            f"at these sampled budgets: {text}."
        )
    lines += [
        "",
        "## Reading the cost trade-off",
        "",
        "`tables/alert_budget_validation.csv` contains every available T0 model, both targets, "
        "both fleet variants and every configured budget, including constant/random floors. "
        "It records realised rates, labelled alert days, false-alert days, missed episodes, "
        "lead time, prevalence and episode counts. `tables/alert_budget_inputs.json` records "
        "SHA-256 hashes of the protocol and input files.",
        "",
        "False-alert days count alerts on negative labelled days. A turbine-month equals the "
        "configured days-per-month amount of labelled turbine-days, not full calendar exposure. "
        "Total alert days also include positive labelled days, but exclude unlabelled days. "
        "Repeated alerts may refer to one episode; there is no cooldown. These counts are "
        "operational burden proxies, not maintenance visits, prevented failures or monetary costs.",
        "",
        "Higher budgets generally detect more episodes while allowing more false-alert "
        "days. Tied counts can leave part of the budget unused. Random alerts can cover more "
        "distinct episode windows than clustered model alerts, especially with a long prediction "
        "window and high prevalence. This helps explain the strong random floor.",
        "",
        "These are descriptive validation point estimates. Model selection and threshold "
        "selection use the same validation period; the sweep adds no uncertainty intervals "
        "or significance claims. Official-budget turbine-bootstrap intervals remain in T0. "
        "Actual maintenance and missed-event costs are unavailable, so no economic optimum "
        "is claimed. Rerun after new models are registered and their validation scores "
        "are available. "
        "Freeze and test-audit status is recorded in `../docs/EVALUATION_REVIEW.md`.",
        "",
        "![Alert burden and missed episodes](figures/04_evaluation/"
        "F27_alert_burden_vs_missed_episodes.png)",
        "",
        "## Reproduce",
        "",
        "```powershell",
        ".venv/Scripts/python.exe scripts/make_baseline_table.py",
        ".venv/Scripts/python.exe scripts/analyse_alert_budgets.py",
        ".venv/Scripts/python.exe scripts/make_report_figures.py --only F15 F27",
        "```",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--interim", type=Path, default=ROOT / "data/interim")
    parser.add_argument("--tables", type=Path, default=ROOT / "reports/tables")
    args = parser.parse_args()
    cfg = load_protocol()
    t0_path = args.tables / "t0_validation.csv"
    t0 = pd.read_csv(t0_path)
    if not t0.split.eq("val").all():
        raise ValueError("T0 must contain validation results only")
    features = pd.read_parquet(args.interim / "features/daily_features.parquet")
    pieces: list[pd.DataFrame] = []
    inputs = [
        ROOT / "configs/protocol.yaml",
        t0_path,
        args.interim / "features/daily_features.parquet",
    ]
    for target in ("a", "b"):
        label_path = args.interim / f"labels/{target}_labels.parquet"
        episode_path = args.interim / f"labels/{target}_episodes.parquet"
        inputs.extend([label_path, episode_path])
        labels = pd.read_parquet(label_path)
        base = labelled(attach_labels(features, labels, cfg), "val")
        episodes = episodes_in_split(pd.read_parquet(episode_path), cfg["splits"]["val_years"])
        for row in t0.loc[t0.target.eq(target.upper())].itertuples(index=False):
            excluded = [] if row.variant == "all" else cfg["baseline_table"]["exclude_stations"]
            expected = "all" if not excluded else "excl_" + "_".join(map(str, sorted(excluded)))
            if row.variant != expected:
                raise ValueError(f"unknown T0 variant {row.variant}")
            frame = base.loc[~base.StationId.isin(excluded), ["StationId", "Day", "split", "label"]]
            path = args.interim / f"scores/{target}_{row.variant}_{row.model}_val.parquet"
            inputs.append(path)
            scores = pd.read_parquet(path)
            frame = frame.merge(scores, on=["StationId", "Day"], how="left", validate="one_to_one")
            if len(frame) != row.n_rows:
                raise ValueError("T0 and prepared validation rows disagree; reproduce T0")
            sweep = budget_sweep(frame, episodes.loc[~episodes.StationId.isin(excluded)], cfg)
            official = sweep.loc[
                sweep.budget.eq(cfg["evaluation"]["false_alarm_budget_per_turbine_month"])
            ]
            checks = ["recall", "pr_auc", "false_alarms_per_turbine_month", "n_episodes"]
            if len(official) != 1 or not all(
                np.isclose(
                    official.iloc[0][key], getattr(row, key), atol=1e-10, rtol=0, equal_nan=True
                )
                for key in checks
            ):
                raise ValueError("scores disagree with T0 at the official budget; reproduce T0")
            pieces.append(sweep.assign(target=target.upper(), variant=row.variant, model=row.model))
    out = add_random_comparison(pd.concat(pieces, ignore_index=True))
    out.to_csv(args.tables / "alert_budget_validation.csv", index=False)
    manifest = {
        str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path): hashlib.sha256(
            path.read_bytes()
        ).hexdigest()
        for path in inputs
    }
    (args.tables / "alert_budget_inputs.json").write_text(json.dumps(manifest, indent=2) + "\n")
    write_readout(
        out, args.tables.parent / "ALERT_BUDGET_ANALYSIS.md",
        float(cfg["evaluation"]["false_alarm_budget_per_turbine_month"]),
    )
    print(f"Wrote {len(out)} validation budget comparisons")


if __name__ == "__main__":
    main()
