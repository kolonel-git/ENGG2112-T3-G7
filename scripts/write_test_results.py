"""Write the single frozen test-year table from the saved runner output (D-061).

Reads ``reports/tables/baselines_a.csv`` and ``baselines_b.csv`` (written by
``scripts/run_baselines.py --frozen``), keeps the test rows, and writes
``reports/tables/test_results.csv`` and ``reports/TEST_RESULTS.md``. It scores nothing and fits
nothing; every number is copied from the runner's table. For each model it also states whether the
95% turbine-bootstrap interval of PR-AUC excludes the random-score floor.

    python scripts/write_test_results.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "reports" / "tables"
KEEP = [
    "target", "model", "n_rows", "n_positive_rows", "prevalence", "n_episodes", "n_detected",
    "threshold", "pr_auc", "pr_auc_lo", "pr_auc_hi", "random_floor_pr_auc", "recall",
    "recall_lo", "recall_hi", "random_floor_recall", "median_lead_days",
    "false_alarms_per_turbine_month", "false_alarms_per_turbine_month_lo",
    "false_alarms_per_turbine_month_hi",
]  # fmt: skip


def load() -> pd.DataFrame:
    frames = []
    for target in ("a", "b"):
        t = pd.read_csv(TABLES / f"baselines_{target}.csv")
        frames.append(t.loc[(t["variant"] == "all") & (t["split"] == "test")])
    table = pd.concat(frames, ignore_index=True)
    if table.empty:
        raise SystemExit("no test rows: run scripts/run_baselines.py --frozen first")
    table = table[KEEP].copy()
    table["target"] = table["target"].str.upper()
    table["pr_auc_interval_excludes_floor"] = (
        table["pr_auc_lo"] > table["random_floor_pr_auc"]
    ) | (table["pr_auc_hi"] < table["random_floor_pr_auc"])
    table["recall_at_or_above_floor"] = table["recall"] >= table["random_floor_recall"]
    return table


def fmt(v: float, lo: float, hi: float, digits: int = 3) -> str:
    return f"{v:.{digits}f} [{lo:.{digits}f}, {hi:.{digits}f}]"


def markdown(table: pd.DataFrame) -> str:
    lines = [
        "# Test-year results (single frozen run)",
        "",
        "Generated by `scripts/write_test_results.py` from the table written by "
        "`scripts/run_baselines.py --frozen` (D-061). Models were fitted on 2016 to 2020 train "
        "years with settings frozen on validation (2021 to 2022); thresholds were chosen on "
        "validation and carried to the test years 2023 to 2026-04. Intervals are 95% percentile "
        "intervals over 1,000 turbine resamples with the threshold held fixed; they do not "
        "include the uncertainty of model or threshold selection. The run was made once and is "
        "not repeated.",
        "",
    ]
    for target in ("A", "B"):
        t = table.loc[table["target"] == target]
        head = t.iloc[0]
        lines += [
            f"## Target {target}",
            "",
            f"{int(head.n_rows):,} labelled turbine-days, {int(head.n_positive_rows):,} positive "
            f"(prevalence {head.prevalence:.3f}), {int(head.n_episodes)} evaluable episodes. The "
            f"random-score floor is PR-AUC {head.random_floor_pr_auc:.3f} and episode recall "
            f"{head.random_floor_recall:.3f}.",
            "",
            "| Model | PR-AUC [95% interval] | Interval excludes floor "
            "| Episode recall [95% interval] | Detected "
            "| False alarms per turbine-month [95% interval] | Median lead (days) |",
            "|---|---|---|---|---:|---|---:|",
        ]
        for r in t.itertuples(index=False):
            lead = "undefined" if pd.isna(r.median_lead_days) else f"{r.median_lead_days:g}"
            fa = (
                r.false_alarms_per_turbine_month,
                r.false_alarms_per_turbine_month_lo,
                r.false_alarms_per_turbine_month_hi,
            )
            lines.append(
                f"| {r.model} | {fmt(r.pr_auc, r.pr_auc_lo, r.pr_auc_hi)} | "
                f"{'yes' if r.pr_auc_interval_excludes_floor else 'no'} | "
                f"{fmt(r.recall, r.recall_lo, r.recall_hi)} | {int(r.n_detected)} / "
                f"{int(r.n_episodes)} | "
                f"{fmt(*fa, 2)} | {lead} |"
            )
        lines.append("")
    lines += [
        "Read with care: the false-alarm rate on test is whatever the validation threshold gives, "
        "so models with a rate above 1 per turbine-month are not at the project's budget and their "
        "recall is not comparable with the floor's at the budget. Positive windows cover about "
        "half of all days, so recall at a fixed false-alarm count is a weak test; compare PR-AUC "
        "with its interval against the floor. Episodes are inferred operational episodes, not "
        "confirmed component failures.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    table = load()
    table.to_csv(TABLES / "test_results.csv", index=False)
    (ROOT / "reports" / "TEST_RESULTS.md").write_text(markdown(table), encoding="utf-8")
    shown = table[
        ["target", "model", "pr_auc", "random_floor_pr_auc", "pr_auc_interval_excludes_floor"]
    ]
    print(shown.round(3).to_string(index=False))
    print(f"wrote {TABLES / 'test_results.csv'} and reports/TEST_RESULTS.md")


if __name__ == "__main__":
    main()
